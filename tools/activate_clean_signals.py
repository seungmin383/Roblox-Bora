"""Promote approved signal meshes and generate their measured lamp layout."""
from pathlib import Path
import json,struct,hashlib,shutil
ROOT=Path(__file__).resolve().parents[1];SRC=ROOT/'assets/traffic/retopology';OUT=ROOT/'assets/traffic/local'
reports=json.loads((SRC/'cleanup-report.json').read_text(encoding='utf-8'));layouts={}
for report in reports:
    name=report['asset'];native=(SRC/f'{name}_Clean.mesh').read_bytes()
    _,stride,_,nv,nf=struct.unpack_from('<HBBII',native,13);start=25
    assert stride==40 and nf==report['after']['triangles']
    rows=[struct.unpack_from('<8f',native,start+i*stride) for i in range(nv)]
    bounds=[max(r[k] for r in rows)-min(r[k] for r in rows) for k in range(3)]
    meta=OUT/('manifest.json' if name=='TrafficSignal' else 'pedestrian-manifest.json')
    manifest=json.loads(meta.read_text(encoding='utf-8'))
    if name=='TrafficSignal':
        optics=report['housing']['rebuiltOptics']
        centres=[[q['centerMeters'][0],q['centerMeters'][1],q['lensPolynomial'][0]-.012] for q in reversed(optics)]
        pitch=(optics[2]['centerMeters'][0]-optics[0]['centerMeters'][0])/2
        extension=[optics[0]['centerMeters'][0]-pitch,optics[0]['centerMeters'][1],optics[0]['lensPolynomial'][0]-.012]
        layouts['Vehicle']={'Bounds':bounds,'Centers':centres,'ExtensionCenter':extension,'Pitch':pitch,
                            'CutX':(optics[0]['centerMeters'][0]+optics[1]['centerMeters'][0])/2}
        # Provenance manifest keeps its original left-to-right lens ordering.
        manifest['lampCentersMeters']=list(reversed(centres));manifest['extensionPitchMeters']=pitch
    else:
        displays=report['housing']['rebuiltDisplays']
        centres=[[d['centerMeters'][0],d['centerMeters'][1],d['screenFrontZ']-.012] for d in displays]
        layouts['Pedestrian']={'Bounds':bounds,'Centers':centres,'LayoutJson':json.dumps(centres,separators=(',',':'))};manifest['lampCentersMeters']=centres
    manifest.update(triangles=nf,vertices=nv,boundsMeters=bounds,activeRevision='Clean approved topology',
                    approvedMeshSha256=hashlib.sha256(native).hexdigest(),approvedMesh=str((SRC/f'{name}_Clean.mesh').relative_to(ROOT)))
    shutil.copyfile(SRC/f'{name}_Clean.mesh',OUT/f'{name}.mesh');shutil.copyfile(SRC/f'{name}_Clean.png',OUT/f'{name}.png')
    meta.write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf-8')
def lua(value):
    if isinstance(value,dict):return '{'+','.join(k+'='+lua(v) for k,v in value.items())+'}'
    if isinstance(value,list):return '{'+','.join(lua(v) for v in value)+'}'
    return repr(value)
(ROOT/'src/TrafficAssetLayout.luau').write_text('-- Measured from the approved Clean signal meshes; generated by activate_clean_signals.py.\nreturn '+lua(layouts)+'\n',encoding='utf-8')
(OUT/'active-layout.json').write_text(json.dumps(layouts,indent=2),encoding='utf-8')
(ROOT/'dist/pedestrian-display-calibration.json').write_text(json.dumps({'CentersMeters':layouts['Pedestrian']['Centers'],'Source':'Approved Clean planar displays'},indent=2),encoding='utf-8')
print('Activated clean vehicle and pedestrian signal meshes:',[(r['asset'],r['after']['triangles']) for r in reports])
